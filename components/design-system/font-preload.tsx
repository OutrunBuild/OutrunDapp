import { readFile, stat } from 'node:fs/promises'
import path from 'node:path'

import { CJK_SUBSET_HREF } from '@/components/design-system/cjk-subset'
import { getDisplayLocale } from '@/lib/locale'

// Font loader — two jobs, both serving "true font on the first frame after refresh":
//
// ① Latin preload backfill: Next 16.3.3~16.4.0 does not emit next/font preload links in the HTML
//    for dynamic route segments (static routes have them, dynamic routes don't; every
//    app/[locale]/** route on this site is affected), so fonts degrade to lazy
//    fetching after CSS parse and even warm-cache refreshes often lose to the first paint →
//    swap paints the fallback then re-dresses (the visible first-paint flicker). This
//    reads Next's build artifact next-font-manifest.json (key=route, value=woff2 files that
//    should be preloaded, Latin .p. files only), takes the union across all routes and re-emits
//    them as <link rel="preload">. Hashed URLs all come from the manifest, zero hardcoding;
//    missing/unreadable manifest = silent fallback to Next's native behavior. crossorigin is
//    mandatory: fonts are fetched in anonymous CORS mode, so a preload without crossorigin never
//    matches the real fetch and is sent for nothing.
//
// ② CJK subset @font-face + preload on zh routes: next/font's Noto is 4 weights × 113 shards =
//    452 non-preloadable faces (the main flash source); replaced with a self-hosted single-file
//    variant subsetting all site copy (scripts/build-cjk-font.mjs, one woff2 with wght 100-900
//    covering all weights). @font-face is inlined here (href and preload single-sourced, artifact
//    content-hash named with immutable caching — globals.css cannot reference dynamic filenames);
//    the family name stays 'Noto Sans SC', zero changes to the tokens.css font stacks. Preload is
//    only emitted on zh routes — en pages consume no CJK glyphs, saving 362KB.

const rawDistDir = process.env.NEXT_DIST_DIR || '.next'
// '..' segments can only be a misconfiguration that silently preloads another
// tree's stale font hashes — fail fast instead of reading the wrong manifest.
if (rawDistDir.split(/[\\/]/).includes('..'))
  throw new Error(`NEXT_DIST_DIR must not contain '..' segments: ${rawDistDir}`)
const DIST_DIR = rawDistDir
// .next is shared by dev(3000) and production preview(4175): server/ = production build,
// dev/server/ = dev incremental artifacts, and the two manifests' font hash names differ
// (production names carry a second hash segment). Pick the manifest matching the run mode;
// picking wrong preloads stale hashes that 404.
const CANDIDATE_PATHS =
  process.env.NODE_ENV === 'development'
    ? [`${DIST_DIR}/dev/server/next-font-manifest.json`, `${DIST_DIR}/server/next-font-manifest.json`]
    : [`${DIST_DIR}/server/next-font-manifest.json`, `${DIST_DIR}/dev/server/next-font-manifest.json`]

let cachedAtMs = -1
let cachedHrefs: string[] = []

async function loadPreloadHrefs(): Promise<string[]> {
  for (const manifestPath of CANDIDATE_PATHS) {
    const absolute = path.resolve(process.cwd(), manifestPath)
    let mtimeMs: number
    try {
      mtimeMs = (await stat(absolute)).mtimeMs
    } catch {
      continue
    }
    if (mtimeMs === cachedAtMs) return cachedHrefs

    try {
      const manifest = JSON.parse(await readFile(absolute, 'utf8')) as {
        app?: Record<string, string[]>
      }
      const files = [...new Set(Object.values(manifest.app ?? {}).flat())]
      cachedHrefs = files.map((file) => `/_next/${file}`)
      cachedAtMs = mtimeMs
      return cachedHrefs
    } catch {
      continue
    }
  }
  return []
}

// Artifacts are content-hash named → href and @font-face share a single source (cjk-subset.ts is
// generated by the build script). font-display:fallback: on a
// cold first visit we accept up to 100ms of invisible text waiting for the font — warm refreshes
// and WiFi·5G cold visits land within the window, so the first frame is Noto with zero flash; on
// 4G cold visits: 0.1s invisible → fallback → swap within 3s (shows up later than swap's "wrong
// font immediately then re-dress", but with more well-timed correctness). The Latin side
// (next/font, fonts.ts) keeps swap untouched — 6 files at only 94KB almost always land in the
// window after preload.
const CJK_FACE_CSS = `@font-face{font-family:'Noto Sans SC';font-style:normal;font-weight:100 900;font-display:fallback;src:url(${CJK_SUBSET_HREF}) format('woff2')}`

export async function FontPreloadLinks() {
  const [hrefs, locale] = await Promise.all([loadPreloadHrefs(), getDisplayLocale()])

  return (
    <>
      <style dangerouslySetInnerHTML={{ __html: CJK_FACE_CSS }} />
      {locale === 'zh' && (
        <link rel="preload" href={CJK_SUBSET_HREF} as="font" type="font/woff2" crossOrigin="anonymous" />
      )}
      {hrefs.map((href) => (
        <link key={href} rel="preload" href={href} as="font" type="font/woff2" crossOrigin="anonymous" />
      ))}
    </>
  )
}
